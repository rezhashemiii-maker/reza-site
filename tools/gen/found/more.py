import re

LRI, PDI = '⁦', '⁩'
_TAG = re.compile(r'<[^>]+>')
_LAT = re.compile(r'[A-Za-z0-9][A-Za-z0-9×⁄²³·.,+\-/()|=<>!^∘∩∪*]*'
                  r'(?:[ ][A-Za-z0-9][A-Za-z0-9×⁄²³·.,+\-/()|=<>!^∘∩∪*]*)*')
_HASLAT = re.compile(r'[A-Za-z]')


def _wrap(m):
    run = m.group(0)
    if not _HASLAT.search(run):
        return run
    tail = ''
    while run and run[-1] in '.,+-/·':
        tail = run[-1] + tail
        run = run[:-1]
    return LRI + run + PDI + tail


def debold(t):
    """«b» را به گیومه بدل می‌کند، چون دادهٔ عبوری از {{...}} به‌صورت متن خام
    نشان داده می‌شود و تگ عیناً دیده می‌شود."""
    return t.replace('<b>', '«').replace('</b>', '»')


def iso(t):
    """لاتینِ داخلِ جملهٔ فارسی را جدا می‌کند و تگ‌ها را دست نمی‌زند."""
    out, last = [], 0
    for m in _TAG.finditer(t):
        out.append(_LAT.sub(_wrap, t[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_LAT.sub(_wrap, t[last:]))
    return ''.join(out)


