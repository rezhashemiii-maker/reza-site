def l(t):
    return ('<span style="direction: ltr; unicode-bidi: isolate; '
            'display: inline-block; font-variant-numeric: tabular-nums;">'
            + t + '</span>')


def strip(cells, box='#15616D'):
    """یک نوارِ خانه‌دار برای نمایشِ پازل — افقی، بدونِ اسکرول."""
    out = ['<span style="display: inline-flex; flex-wrap: wrap; gap: 4px; '
           'direction: ltr; unicode-bidi: isolate; margin: 2px 0;">']
    for c in cells:
        full = c not in ('·', '')
        out.append(
            '<span style="width: 26px; height: 30px; display: inline-flex; '
            'align-items: center; justify-content: center; font-size: 14px; '
            'font-weight: %s; border: 1px solid %s; border-radius: 5px; '
            'background: %s; color: %s;">%s</span>'
            % ('800' if full else '400',
               box if full else '#D9D4C7',
               '#FFFFFF' if full else '#FAFAF7',
               box if full else '#B9B3A5',
               c if full else '·'))
    out.append('</span>')
    return ''.join(out)


