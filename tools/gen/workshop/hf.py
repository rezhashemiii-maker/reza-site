def _is_fa(t):
    return any('\u0600' <= c <= '\u06FF' for c in t)


def sec(sid, eyebrow, title, white=False, top=True):
    bg = '#FFFFFF' if white else 'transparent'
    bd = ('border-top: 1px solid %(LINE)s; border-bottom: 1px solid %(LINE)s;' % V) if white else ''
