    w('''        <p style="font-size: 13.5px; line-height: 1.95; color: #666158; margin: 0 0 18px;">این راهنما اسکلت کار است، نه نسخهٔ پیچیده‌شده: گام‌ها از مرحلهٔ همین پروژه و دیتاست و مهارت‌های خودش ساخته شده‌اند. تصمیم‌های ریز را خودت می‌گیری — که اصلاً نکتهٔ پروژه همین است.</p>
        <div style="display: flex; flex-direction: column; gap: 12px;">''')
    for lab, body in steps:
        w('''          <div style="display: flex; gap: 12px; align-items: stretch;">
            <div style="flex-shrink: 0; width: 42px; font-size: 11.5px; font-weight: 700; color: #2F5233; padding-top: 3px;">%s</div>
            <div style="flex: 1; min-width: 0; padding-inline-start: 14px; border-inline-start: 2px solid #D5DDD2; font-size: 14px; line-height: 2.05; color: #45494F;">%s</div>
          </div>''' % (lab, body))
