export function getPages(root) {
  const pages = CORE_PAGES.map(([file, out, nav, description]) => ({ file, out, nav, description }));
  const src = path.join(root, 'src');
  for (const file of fs.readdirSync(src).filter((f) => /^Aie\d{3}\.dc\.html$/.test(f)).sort()) {
    const tree = parse(fs.readFileSync(path.join(src, file), 'utf8'));
    const main = find(tree, 'main');
    const title = rawTextOf(find(main, 'h1') || find(tree, 'title') || { kids: [] }).trim();
    const summary = rawTextOf(find(main, 'p') || { kids: [] }).replace(/\s+/g, ' ').trim();
    if (!title || !summary) throw new Error(`${file}: عنوان و خلاصهٔ پروژه برای متادیتا لازم است`);
    pages.push({
      file,
      out: `aie-${file[3]}-${file.slice(4, 6)}.html`,
      nav: 'پروژه',
      description: `${title}؛ ${summary}`,
    });
  }
  return pages;
}
